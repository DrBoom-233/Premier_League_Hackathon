// Run against the local API with a completed REAL case from the development audit; no paid POST.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.PITCHGUARD_BASE_URL || 'http://127.0.0.1:8000';
(async()=>{
  const audit=JSON.parse(fs.readFileSync('evaluation/development_runs.json','utf8'));
  const record=[...audit].reverse().find(c=>c.scenario_id==='S002'&&c.mode==='multi'&&c.state==='completed');
  assert(record,'Run a real S002 analysis first');
  const browser=await chromium.launch({headless:true,channel:process.env.BROWSER_CHANNEL || 'msedge'});
  try {
  const page=await browser.newPage({viewport:{width:1440,height:1050}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  let paidPosts=0;page.on('request',r=>{if(r.method()==='POST'&&r.url().endsWith('/api/analyses'))paidPosts++;});
  await page.goto(`${base}/?scenario=S002&case=${record.id}`);
  await page.getByText('Machine output · human validation pending').waitFor();
  assert(await page.getByText('1574.6',{exact:false}).count());
  const history=page.getByRole('region',{name:'Player history assessment'});
  await history.getByText('Historical Agent assessment',{exact:true}).waitFor();
  assert.equal(await history.locator('.history-agent-output .history-agent-claim').count(),3);
  assert.match(await history.innerText(),/393 minutes/);
  assert.match(await history.innerText(),/Included in investigator input/);
  assert.match(await history.innerText(),/Completed · cached/i);
  await history.getByText('All historical metrics and prior events',{exact:true}).click();
  assert.equal(await history.locator('tbody tr').count(),16);
  await history.getByText('Prior events known at the cutoff',{exact:true}).waitFor();
  assert(await history.getByRole('button',{name:'INJ_P001_0001',exact:true}).count());
  await history.locator('.citations button').first().click();
  await page.locator('.evidence-detail pre').waitFor();
  assert.match(await page.locator('.evidence-detail').innerText(),/daily_records.csv/);
  const citation=page.locator('.citations button').filter({hasText:'S002_'}).first();
  await citation.click();
  await page.locator('.evidence-detail img').waitFor();
  const frameText=await citation.innerText();
  const expected=(Number(frameText.split('_F')[1])-1)/24;
  const actual=await page.locator('video').first().evaluate(el=>el.currentTime);
  assert(Math.abs(expected-actual)<.1,'Evidence click must seek the correct timestamp');
  await page.waitForFunction(()=>[...document.querySelectorAll('video')].every(v=>v.readyState>=2&&!v.seeking));
  await page.screenshot({path:'.tools/demo-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Fan view',exact:true}).click();
  await page.locator('.insight-top .eyebrow').filter({hasText:'FROM THE TOUCHLINE'}).waitFor();
  await page.waitForFunction(()=>document.querySelectorAll('.claim').length>0);
  assert.equal(await page.locator('.history-panel').count(),0);
  assert.equal(await page.locator('.evidence-detail pre').count(),0);
  const fan=await page.request.get(`${base}/api/analyses/${record.id}?audience=fan`);
  const fanData=await fan.json();
  for (const privateField of ['history','history_output','decision','trace']) assert(!(privateField in fanData));
  assert(Object.values(fanData.evidence).every(e=>e.kind==='frame'));
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>[...document.querySelectorAll('video')].every(v=>v.readyState>=2&&!v.seeking));
  await page.screenshot({path:'.tools/demo-mobile.png',fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile horizontal overflow');
  await page.getByRole('button',{name:/Replay 3/}).click();
  await page.waitForFunction(()=>!document.querySelector('.claim'));
  await page.getByRole('button',{name:'Analyst',exact:true}).click();
  await page.getByText('Click Analyze replay or open a saved analysis to load historical metrics and the agent assessment.').waitFor();
  assert.equal(paidPosts,0);
  assert.deepEqual(errors,[]);
  console.log('PASS: historical assessment/cache/participation/source display, empty state, source seeking, fan privacy, mobile layout; no paid POST.');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
